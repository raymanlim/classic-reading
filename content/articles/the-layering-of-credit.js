把以上放在一起，结论可以收紧成一句话：**信任不是道德资源，而是基础设施。它不能被外包，只能被分层转移；每一层转移都降低单笔成本，同时新增一个需要被信任的节点。**

据此可以给出三个判据，用来判断某一层信任安排是否可靠：

1. **违约能否被低成本发现。** 不是「有没有规则」，而是普通人要花多少代价才能知道对方违约了。信息不对称越深，规则越像装饰。
2. **发现之后是否有真实后果。** 后果必须是具体的、可执行的，而不是名义上的。一个只能起诉、无法执行的契约，等于没有契约。
3. **退出是否可能。** 这一条最容易被忽略。如果你无法退出，那么你与对方的关系就不是信任，而是依赖——依赖不需要信任，它只需要服从。

