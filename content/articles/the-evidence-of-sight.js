这一层反方之所以有力，是因为它把指责的对象从「图像」换成了「制度」。如果问题出在图像本身，那我们只能少看图；但如果问题出在**担保制度**——谁拍的、什么时候拍的、有没有被裁切、有没有独立来源——那它是可以被修复的。

