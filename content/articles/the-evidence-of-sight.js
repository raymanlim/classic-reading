但修复也有它的限度，而且这个限度很容易被越过。

第一种越界，是**图像恐惧症**。如果每一张照片都是取景、都是解释、都可能被操纵，那么最「安全」的立场就是什么图都不信。可这个立场会走向自我否定：如果视觉不可信，文字就可信吗？文字同样有取景框——选题、措辞、引文、删节。把不信任从图像扩展到一切表征，最后剩下的不是清醒，而是失语。

第二种越界，是**技术万能论**。现在有一整套方案在解决「这张图是不是真的」：内容凭证、密码学签名、拍摄设备的时间与位置水印。这些工具有用，但它们回答的是「这张图是谁、在何时、用什么设备产生的」，不回答「这张图被用来主张什么」。**溯源能证明来源，不能证明含义。** 把社会信任问题当成技术问题，是另一种偷懒。

第三种越界，是**彻底的第一手主义**。既然二手不可靠，那就只信自己亲眼所见。可一个人一生能亲眼见的，只是极小的一部分；绝大多数关于世界的事实，我们只能通过别人、通过设备、通过记录来知道。拒绝一切二手，不是严谨，而是放弃认识世界。

所以，真正的限度在这里：**我们不能靠「更少地看」或「更技术地看」来解决一个制度问题。** 图像批判如果停在「图像不可信」，它只是把怀疑从一个对象转移到另一个对象，而没有重建任何东西。

