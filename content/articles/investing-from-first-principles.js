第一性原则是否可靠，不能在顺风里检验，因为那时任何方法看起来都有效。一个更严格的做法是做逆向思想实验：想象一个极端年份，市场连续下跌、坏消息不断、你身边所有人都改变说法，然后逐条问——我写下的规则会不会让我在底部卖出？

