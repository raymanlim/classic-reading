J. E. 戈登在《结构：为什么东西不会倒塌》里反复强调的一点是：结构失效很少源于算错，更多源于裂纹、疲劳、腐蚀，以及没有人注意到它们。安全系数不是工程师无知的遮羞布，而是对「我们不知道的东西」的定价——对荷载的不确定、对材料离散性的不确定、对未来使用方式的不确定。这个定价只有在被持续复核时才有意义；一旦复核停止，安全系数就变成了一个写在图纸上的、无人兑现的承诺。

