这个区分画出一条很硬的界线：**凡是能被完整写下来的，就能被直接教；凡是不能被完整写下来的，就只能自己长出来。** 而前者恰好是价值较低的那一半——因为它能被写下来，也就能被抄走、被检索、被自动化。这解释了一个反复出现的现象：在任何一个知识变得容易获取的时代，教育的内容都会被迫上移，而上移之后剩下的，正是最难教的那部分。

